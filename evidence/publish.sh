#!/usr/bin/env bash
# Publishes latest.json and the HTML reports of this run to the gh-pages branch (served by GitHub Pages):
#   /evidence/latest.json, /evidence/<sha>.json, /evidence/bom.json
#   /reports/playwright/, /reports/jacoco/, /reports/pit/
# Needs GH_TOKEN, REPO and SHA, and reports/ as downloaded by the evidence job.
set -euo pipefail
site=$(mktemp -d)
remote="https://x-access-token:${GH_TOKEN}@github.com/${REPO}.git"

if git ls-remote --exit-code --heads "$remote" gh-pages >/dev/null 2>&1; then
  git clone --quiet --depth 1 --branch gh-pages "$remote" "$site"
else
  git init --quiet "$site"
  git -C "$site" checkout --quiet --orphan gh-pages
  git -C "$site" remote add origin "$remote"
fi

rm -rf "$site/reports"
mkdir -p "$site/evidence" "$site/reports"
cp latest.json "$site/evidence/latest.json"
cp latest.json "$site/evidence/${SHA}.json"
cp reports/sbom/application.cdx.json "$site/evidence/bom.json" 2>/dev/null || true
[ -d reports/playwright-report/playwright-report ] && cp -r reports/playwright-report/playwright-report "$site/reports/playwright"
[ -d reports/jacoco-report ] && cp -r reports/jacoco-report "$site/reports/jacoco"
[ -d ledgerline-api/target/pit-reports ] && cp -r ledgerline-api/target/pit-reports "$site/reports/pit"
touch "$site/.nojekyll"

cat > "$site/index.html" <<HTML
<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Ledgerline evidence</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:46rem;margin:2rem auto;padding:0 1rem}code{font-size:.9em}</style></head>
<body>
<h1>Ledgerline engineering evidence</h1>
<p>SpecShield Labs internal demonstration, synthetic data only. Generated by CI for commit <code>${SHA}</code>;
every number comes from a report of that run or the latest scheduled run, and is null when not measured.</p>
<ul>
<li><a href="evidence/latest.json">evidence/latest.json</a></li>
<li><a href="reports/playwright/">Playwright end-to-end report</a></li>
<li><a href="reports/jacoco/">JaCoCo coverage report</a></li>
<li><a href="reports/pit/">PIT mutation report</a></li>
<li><a href="evidence/bom.json">CycloneDX SBOM</a></li>
<li><a href="https://github.com/${REPO}">Source on GitHub</a></li>
</ul>
</body>
</html>
HTML

cd "$site"
git add -A
if git diff --cached --quiet; then
  echo "gh-pages already up to date"
  exit 0
fi
git -c user.name="github-actions[bot]" -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
  commit --quiet -m "Evidence for ${SHA}"
git push --quiet origin gh-pages
echo "published evidence for ${SHA}"
